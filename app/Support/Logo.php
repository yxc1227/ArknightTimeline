<?php

namespace App\Support;

/**
 * 项目标记（logo）的几何定义 —— 唯一信息源。
 *
 * ## 是什么
 *
 * 一个 32×32 的矢量标记：整幅斜切方块 + 墨色字母组合「AT」。
 * 「AT」= Arknights Timeline，沿用原顶栏 `AT` 方块的识别度；
 * 但字形不再是字体渲染的文字，而是按网格画出来的原创几何。
 *
 * ## 三个母题（都来自 docs/DESIGN.md §1.4，不是凭空造型）
 *
 *   1. **斜切方块**：外框右下角 9 单位的斜切，比例与 `.btn--primary` 的
 *      clip-path（28px 上切 8px ≈ 0.29）一致 —— 标记与界面是同一套形状语言。
 *   2. **A 的平顶**：字母 A 的顶点不做尖角而切平 3.5 单位，是斜切母题在字内的重现；
 *      两条腿水平厚度恒为 3.0，保证任意高度下线宽不变（几何无衬线，非字体）。
 *   3. **基准轴**：字母下方一条贯通字组全宽的细横线（1.4 单位厚，与字母留 1.1 单位空隙）。
 *      它是整个标记唯一的一处语义细节 —— 时间轴托着事件。
 *      位置上刻意避开方块的斜切角，跨度正好等于字组宽度，因此读起来是「基座」而不是「下划线」。
 *      它同时解决了构图问题：字母原本悬在方块上半部，下方留下近 9 单位空白，
 *      加了这条轴之后墨迹上下留白为 8.5 / 7.0，整枚标记才立得住。
 *
 *      （这一处改过两版，都否决了：把节点画成轴上嵌方块并留空隙 —— 竖笔一断，
 *      T 立刻被读成「T ！」的残字；把节点改成横跨竖笔的刻度 —— 又变成两道横笔，
 *      T 读成「‡」。结论是细节不能动字母本身，只能另起一个元素承载语义。）
 *
 * ## 边界
 *
 * 全部为原创几何，**不描摹鹰角网络的任何官方标识**（与全站「不使用官方素材」同一条红线）。
 *
 * ## 改动须知
 *
 * 改这里的坐标，等于改全站标记：顶栏（`<x-logo>` 组件）、
 * 浏览器标签图标（`public/favicon.svg` / `favicon.ico`）与
 * `docs/logo-preview.html` 都由它派生。改完请重新生成后两者（见 docs/LOGO.md §6）。
 */
final class Logo
{
    /** 画布：32×32，整幅铺满（无透明留白），因此可直接当 favicon 几何用。 */
    public const VIEW_BOX = '0 0 32 32';

    /** 外框：右下角 9 单位斜切，与 .btn--primary 的切角比例一致。 */
    public const CONTAINER = 'M0 0H32V23L23 32H0Z';

    /**
     * 字形 path 列表。**每一项都渲染成独立的 <path>**，这一点是硬约束：
     * 组件对整组字形施加 fill-rule="evenodd"，若两个**形状**写进同一条 path
     * （即成为同一条 path 的子路径），重叠区会被 evenodd 异或成空洞。
     * 只有 A 的「外轮廓 + 两个内孔」必须保持同处一条 path，那是刻意的挖空。
     *
     * 字面高 14 单位（y 7.5–21.5），腿厚恒为 3.0；基准轴在 23.3–24.7。
     * 字母距上下边 7.5 / 7.3 —— 近乎精确居中；
     * 「基线 → 轴」留 1.8 单位，是为了 16px 的标签页图标：那里 1 单位只有 0.5px，
     * 间隙再小就会被抗锯齿糊成一体，字母会像踩在一块砖上。
     */
    public const GLYPH = [
        // A：外轮廓 + 上内孔 + 下内孔（同一条 path 的子路径，靠 evenodd 挖空）
        'M9.65 7.5H13.15L16.65 21.5H6.15Z'
            . 'M11.4 12.5L10.63 15.6H12.18Z'
            . 'M9.93 18.4H12.88L13.65 21.5H9.15Z',
        // T 横笔
        'M19 7.5H26V10.3H19Z',
        // T 竖笔
        'M20.9 10.3H24.1V21.5H20.9Z',
        // 基准轴：时间轴。跨度 = 字组宽度（6.15–26）
        'M6.15 23.3H26V24.7H6.15Z',
    ];

    /** 方块色 = 标志黄（与 --accent 同值）。 */
    public const COLOR_BOX = '#ffd400';

    /** 字母色 = 近黑墨色（与 --accent-ink 同值）。 */
    public const COLOR_INK = '#0d0d0d';

    /**
     * 生成独立可用的 favicon SVG（色值内联）。
     *
     * 为什么单独生成而不是直接引用组件：`public/*.svg` 是脱离页面的静态文件，
     * 拿不到 CSS 变量与 currentColor，因此这里把配色写死为常量；
     * 页面内的标记仍由组件的 CSS 类上色。两处颜色都取自上面的常量，不会分叉。
     */
    public static function faviconSvg(): string
    {
        $paths = '';
        foreach (self::GLYPH as $d) {
            $paths .= '<path d="' . $d . '"/>';
        }

        return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="' . self::VIEW_BOX . '" width="32" height="32">'
            . '<!-- 由 App\Support\Logo 生成：改标记请改该文件后重新生成（docs/LOGO.md §6） -->'
            . '<path fill="' . self::COLOR_BOX . '" d="' . self::CONTAINER . '"/>'
            . '<g fill="' . self::COLOR_INK . '" fill-rule="evenodd">' . $paths . '</g>'
            . '</svg>';
    }
}
