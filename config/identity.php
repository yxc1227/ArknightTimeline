<?php

return [

    /*
    |--------------------------------------------------------------------------
    | 外部身份（登录 / 注册 / 绑定）
    |--------------------------------------------------------------------------
    |
    | 设计要点：**提供方是配置，不是代码**。
    |
    | 每个提供方都通过同一套 OAuth2 授权码流程接入，差异全部收敛在这里的
    | 端点与字段映射（mapping）中。这样接入一个新的外部渠道只需要加一段配置，
    | 而不是复制一遍控制器 —— 也就不会出现「某个渠道的 state 校验被漏掉」。
    |
    | ⚠️ 关于「鹰角通行证」的重要说明：
    | 鹰角网络并未提供面向第三方的公开 OAuth 接口，因此这里**不预置任何猜测出来的
    | 端点**（逆向其私有接口既违反服务条款，也会随对方改版随时失效）。
    | 未配置凭据时该渠道显示为「未启用」，用户看到的是诚实的不可用状态，
    | 而不是一个点了会报错的按钮。一旦获得正式凭据，只需填写下面的环境变量即可启用，
    | 无需改代码。在启用之前，「绑定鹰角账号」走 allow_manual 的手工登记路径。
    |
    | 另外：本系统在任何情况下都不收集、不中转用户的外部账号密码。
    | 绑定必须由用户在他自己的浏览器里完成授权，见 IdentityManager 的类注释。
    |
    */

    'providers' => [

