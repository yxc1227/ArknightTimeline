            'client_secret' => env('HYPERGRYPH_CLIENT_SECRET'),

            'authorize_url' => env('HYPERGRYPH_AUTHORIZE_URL'),
            'token_url' => env('HYPERGRYPH_TOKEN_URL'),
            'userinfo_url' => env('HYPERGRYPH_USERINFO_URL'),

            'scopes' => ['openid', 'profile'],

            // 响应字段 → 本系统字段。支持点号路径（如 'data.user.id'）。
            'mapping' => [
                'id' => 'sub',
                'nickname' => 'nickname',
                'avatar' => 'picture',
                'email' => 'email',
            ],

            /*
             * 手工登记：在正式 OAuth 凭据到位之前，「绑定鹰角账号」唯一能真正走通的路径。
             * 用户提交自己的通行证 UID，落为 pending，由管理员在账号详情页核验后转 verified。
             * 对外展示时会明确区分「已登记」与「已核验」—— 不能让人把自助声明当成官方认证。
             */
            'allow_manual' => true,
            'manual_label' => '通行证 UID',
            'manual_hint' => '在游戏内「设置 → 账号」或森空岛个人主页可以找到这串数字。'
                .'提交后需管理员核验；核验方式是人工确认，不代表鹰角网络官方认证。',
        ],

        /*
         * 本地演示渠道。
         *
         * 它让「外部注册 → 完善资料 → 绑定 / 解绑」这条链路在没有真实凭据的
         * 环境里也能完整走通（并让测试能覆盖 state 校验等分支）。
         * 因为它是**任何人点一下就登录**的通道，绝不允许出现在非本地环境，
         * 所以启用条件写死在配置里，而不是留给部署时去记得关掉。
         */
        'stub' => [
            'driver' => 'stub',

            /*
             * 用 env('APP_ENV') 而不是 app()->environment()：配置文件在容器把 'env'
             * 绑定起来之前就被加载了，此时调用 app()->environment() 会去解析一个
             * 名为 env 的类并抛 «Target class [env] does not exist» —— 整个应用起不来。
             * 配置文件里只能用 env()，这也是唯一在 config:cache 时行为正确的写法
             * （生产环境缓存配置时会把这里固化成 false）。
             */
            'enabled' => in_array(env('APP_ENV', 'production'), ['local', 'testing'], true),

            'label' => '本地演示账号',
            'short' => 'LOCAL STUB',
